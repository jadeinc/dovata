//! Generate the C header (`include/jade_protocol.h`) from the FFI surface.
//! Non-fatal: a cbindgen hiccup must not block building the library itself.

fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=src/stream.rs");

    let crate_dir = match std::env::var("CARGO_MANIFEST_DIR") {
        Ok(d) => d,
        Err(_) => return,
    };
    let out = std::path::Path::new(&crate_dir).join("include").join("jade_protocol.h");

    let bindings = cbindgen::Builder::new()
        .with_crate(&crate_dir)
        .with_language(cbindgen::Language::C)
        .with_pragma_once(true)
        .with_documentation(true)
        .with_header("/* Generated by cbindgen from jade-protocol-ffi. Do not edit by hand. */")
        .generate();

    if let Ok(bindings) = bindings {
        if let Some(parent) = out.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        bindings.write_to_file(&out);
    }
}
